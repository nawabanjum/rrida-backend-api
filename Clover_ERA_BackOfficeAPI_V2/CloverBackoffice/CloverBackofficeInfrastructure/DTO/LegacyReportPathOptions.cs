namespace CloverBackoffice.Infrastructure.DTO
{
    // Kill switches for the report-generating paths that predate the scheduled
    // flow. Bound to "LegacyReportPaths" in appsettings.json.
    //
    // The AppSettings-configured background service
    // (ReportSchedulerBackgroundService → GuardShortageJob.RunJobListAsync) is
    // the authoritative automated report-generation flow. Every switch here is
    // an ALTERNATIVE way a report could be created and published, bypassing the
    // schedule, the licence gate and the admin review step. They default to
    // false — disabled — and the code behind them is left fully intact so any
    // of them can be brought back by flipping a flag, with no redeploy of new
    // logic.
    //
    // Disabling a path never disables the endpoint's other work: batch polling,
    // batch metadata and EngagementInsights all keep running. Only the
    // create-report / publish-report portion is skipped.
    public class LegacyReportPathOptions
    {
        // GET /api/feedbackanalysis/get-analysis-by-days
        // Ran an ad-hoc analysis and, as a side effect of a GET, created AND
        // published a report for the unit with no licence check and no review.
        public bool AnalyzeByDaysEnabled { get; set; } = false;

        // RagService.SaveEngagementInsightsAsync, reached from
        // the batch-poll job (BatchPollingBackgroundService).
        // Deleted any report for the unit inside the last 14 days and replaced
        // it with a freshly published one — directly overlapping the bi-weekly
        // cycle the scheduler owns.
        public bool BatchPollPublishEnabled { get; set; } = false;

        // POST /api/rag/approved-batchinsights-manually
        // Published a report straight from posted batch-insight JSON.
        public bool ManualBatchInsightsEnabled { get; set; } = false;

        // Shared message so every disabled path explains itself the same way.
        public const string DisabledMessage =
            "This report path is disabled. Bi-weekly reports are generated by the scheduled " +
            "background job and released through the admin review queue " +
            "(api/report-approvals). Re-enable under LegacyReportPaths in appsettings if needed.";
    }
}
