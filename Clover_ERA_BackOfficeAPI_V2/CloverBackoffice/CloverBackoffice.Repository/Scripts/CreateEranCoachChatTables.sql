-- =====================================================================
-- EranCoach — persistent chat: Conversations + Messages
-- Run this manually against the CloverBackoffice PostgreSQL database.
--
-- Backs the EranCoachConversation + EranCoachMessage entities + DbSets
-- (no EF migration is used for these tables; the schema is applied via
-- this script — same approach as CreateCloveraPersonalSnapshots.sql).
-- Column types match exactly what EF Core / Npgsql maps the entities to,
-- so the entities read/write the tables with no further configuration.
--
-- Requirement 1 (central model config) uses OPTION A: it reuses the
-- existing "ModelConfiguration" table (Search type, ModelConfigTypeId = 1)
-- and flags the active coach model via its "IsSelected" column. No new
-- table is needed for it — only the two chat tables below are created.
--
-- Idempotent: safe to run more than once.
-- =====================================================================

-- ── Conversations ────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public."EranCoachConversations"
(
    "Id"             integer                  GENERATED BY DEFAULT AS IDENTITY,

    -- Owner (Users.UserId). Every read/write is scoped by this.
    "UserId"         integer                  NOT NULL,

    "Title"          character varying(200),
    "IsPinned"       boolean                  NOT NULL DEFAULT false,

    -- Scope snapshot captured at creation (nullable; best-effort).
    "CompanyId"      bigint,
    "BusinessUnitId" bigint,
    "UserGroupId"    integer,

    "LastMessageAt"  timestamp with time zone,

    "CreatedAt"      timestamp with time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    "UpdatedAt"      timestamp with time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    "IsDel"          boolean                  NOT NULL DEFAULT false,

    CONSTRAINT "PK_EranCoachConversations" PRIMARY KEY ("Id")
);

-- Owner list view: their non-deleted chats, pinned first, most-recent first.
CREATE INDEX IF NOT EXISTS "IX_EranCoachConversations_UserId_IsDel_LastMessageAt"
    ON public."EranCoachConversations" ("UserId", "IsDel", "LastMessageAt");

-- ── Messages ─────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public."EranCoachMessages"
(
    "Id"               bigint                   GENERATED BY DEFAULT AS IDENTITY,

    "ConversationId"   integer                  NOT NULL,
    "Role"             character varying(20)    NOT NULL,          -- 'user' | 'assistant'
    "Content"          text                     NOT NULL,

    -- Optional telemetry.
    "PromptTokens"     integer,
    "CompletionTokens" integer,
    "ModelUsed"        character varying(120),

    "CreatedAt"        timestamp with time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    "IsDel"            boolean                  NOT NULL DEFAULT false,

    CONSTRAINT "PK_EranCoachMessages" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EranCoachMessages_EranCoachConversations_ConversationId"
        FOREIGN KEY ("ConversationId")
        REFERENCES public."EranCoachConversations" ("Id")
        ON DELETE CASCADE
);

-- Transcript load: a conversation's messages in chronological order.
CREATE INDEX IF NOT EXISTS "IX_EranCoachMessages_ConversationId_CreatedAt"
    ON public."EranCoachMessages" ("ConversationId", "CreatedAt");
