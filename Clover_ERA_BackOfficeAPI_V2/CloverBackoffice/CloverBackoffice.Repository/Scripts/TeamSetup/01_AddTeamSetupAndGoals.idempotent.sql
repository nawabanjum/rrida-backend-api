--
-- RRIDA Team Setup. Everything the setup wizard captures beyond the name and size
-- the business unit already holds.
--
--   TeamSetups      one live row per unit: the team type and the manager's context.
--                   The row existing is what "this team has been set up" means, so
--                   there is no completed flag and nothing nullable to interpret.
--   TeamGoals       two to five goals per unit, ordered, soft-deleted. The count is
--                   a wizard rule the API enforces; no row constraint can count
--                   siblings.
--   TeamGoalAudits  one snapshot row per goal operation - INSERT, UPDATE, DELETE or
--                   REORDER - carrying the whole goal as it stood, who changed it and
--                   when. No foreign key back to TeamGoals, the same choice
--                   CustomQuestionAudits and TeamDailyFeedbackAuditLogs make, so the
--                   history outlives even a hard delete.
--
-- Three new tables. NOTHING EXISTING IS ALTERED. BusinessUnits already carries the
-- team name, TeamSize and BusinessUnitShortCode (the invite code), and is left alone
-- deliberately: ten foreign keys point at it and it serves the legacy CLOVER product
-- as well as RRIDA.
--
-- Foreign keys are ON DELETE RESTRICT throughout, matching CustomQuestions and
-- TeamDailyFeedback: a company or unit holding setup rows must not be deleted out
-- from under them.
--
-- This file is the exact output of
--     dotnet ef migrations script 20260827114040_AddUnitIdToCustomQuestionDailyFeedback \
--                                 20260831095121_AddTeamSetupAndGoals --idempotent
-- with only this header, the pre-flight check and the rollback note added, so the
-- script and migration 20260831095121_AddTeamSetupAndGoals cannot drift apart.
--
-- Safe to run more than once: every statement is guarded on the migration history
-- row, and the whole script is one transaction, so a failure leaves the database
-- untouched. Running it also writes the __EFMigrationsHistory row, so EF will not
-- try to apply the same migration again.
--
-- Prerequisites: migrations up to 20260827114040 already applied.
-- Target: PostgreSQL, database rrida. Run the file as a whole in pgAdmin, not
-- statement by statement, or the transaction boundary is lost.
-- =============================================================================

