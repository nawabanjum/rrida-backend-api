-- =====================================================================
-- DocumentEmbeddings — shared pgvector store (RAG). EranCoach's retrieval
-- tools and POST /seed-corpus read/write this table (namespace column
-- "EmbeddingType" = 'eran_coach_corpus').
-- Run this manually against the CloverBackoffice PostgreSQL database.
--
-- Ships via EF migration AddDocumentEmbeddingsWithPgVector; create it with
-- this script on databases where migrations were not applied. Columns match
-- the DocumentEmbedding entity; the vector column + HNSW cosine index match
-- ApplicationDbContext.OnModelCreating.
--
-- Idempotent: safe to run more than once.
-- =====================================================================

-- pgvector must be available for the vector(1536) column + HNSW index.
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS public."DocumentEmbeddings"
(
    "Id"            integer                  GENERATED BY DEFAULT AS IDENTITY,
    "Title"         character varying(500)   NOT NULL,
    "Content"       text                     NOT NULL,
    "Embedding"     vector(1536)             NOT NULL,
    "SourceType"    character varying(100)   NOT NULL,
    "FileName"      character varying(500),
    "ChunkIndex"    integer,
    "EmbeddingType" character varying(200),
    "ProcessId"     integer                  NOT NULL DEFAULT 0,
    "CreatedAt"     timestamp with time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    "UpdatedAt"     timestamp with time zone,
    CONSTRAINT "PK_DocumentEmbeddings" PRIMARY KEY ("Id")
);

-- Approximate-nearest-neighbour index for cosine similarity search.
CREATE INDEX IF NOT EXISTS "IX_DocumentEmbeddings_Embedding"
    ON public."DocumentEmbeddings" USING hnsw ("Embedding" vector_cosine_ops);

-- Corpus queries filter by namespace + source, so index those too.
CREATE INDEX IF NOT EXISTS "IX_DocumentEmbeddings_EmbeddingType_SourceType"
    ON public."DocumentEmbeddings" ("EmbeddingType", "SourceType");
