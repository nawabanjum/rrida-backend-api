-- 08_AddManagerActionComments.idempotent.sql
--
-- Comments on a manager's own (manual) action: POST api/actions/{id}/comments.
--
--   ManagerActionComments  one row per comment: ManagerActionId (FK to
--                          ManagerActions), Text (<= 500), CreatedBy (the
--                          logged-in user), CreatedAt, IsDel. Index on
--                          ManagerActionId for the action's comments.
--
-- New table only; nothing existing is changed. Comments on engine actions stay
-- in TeamActionComments.
--
-- Run AFTER 06_AddManagerActions and 07_ManagerActionsTeamOnly.
--
-- Exact output of
--     dotnet ef migrations script 20261116135604_AddTeamSizeHistory \
--                                 20261116182804_AddManagerActionComments --idempotent
-- with only this header and the summary SELECT added.
--
-- Safe to run more than once (guarded on the migration history row), one
-- transaction. Run the whole file in pgAdmin (F5). Run BEFORE deploying: the
-- api/actions read paths query this table.
-- =============================================================================

START TRANSACTION;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20261116182804_AddManagerActionComments') THEN
    CREATE TABLE public."ManagerActionComments" (
        "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
        "ManagerActionId" bigint NOT NULL,
        "Text" character varying(500) NOT NULL,
        "CreatedBy" integer NOT NULL,
        "CreatedAt" timestamp with time zone NOT NULL,
        "IsDel" boolean NOT NULL,
        CONSTRAINT "PK_ManagerActionComments" PRIMARY KEY ("Id"),
        CONSTRAINT "FK_ManagerActionComments_ManagerActions_ManagerActionId" FOREIGN KEY ("ManagerActionId") REFERENCES public."ManagerActions" ("Id") ON DELETE RESTRICT
    );
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20261116182804_AddManagerActionComments') THEN
    CREATE INDEX "IX_ManagerActionComments_Action" ON public."ManagerActionComments" ("ManagerActionId") WHERE "IsDel" = false;
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20261116182804_AddManagerActionComments') THEN
    INSERT INTO "__EFMigrationsHistory" ("MigrationId", "ProductVersion")
    VALUES ('20261116182804_AddManagerActionComments', '9.0.1');
    END IF;
END $EF$;
COMMIT;



-- Summary
SELECT
    (SELECT COUNT(*) FROM "__EFMigrationsHistory"
      WHERE "MigrationId" = '20261116182804_AddManagerActionComments')           AS migration_applied,
    (SELECT string_agg(column_name, ', ' ORDER BY ordinal_position) FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'ManagerActionComments')    AS columns,
    (SELECT string_agg(indexname, ', ' ORDER BY indexname) FROM pg_indexes
      WHERE schemaname = 'public' AND tablename = 'ManagerActionComments')       AS indexes,
    (SELECT COUNT(*) FROM public."ManagerActionComments")                        AS comment_rows;
