-- RRIDA Team Health milestones ("+ Add milestone" on the Team Health timeline).
--
--   TeamMilestones  one row per milestone: team (ProfileId + UnitId), title
--                   (<= 40 chars), description (<= 200 chars) and the date it
--                   happened. Soft-deleted via IsDel.
--
-- One new table. NOTHING EXISTING IS ALTERED, and no Team Health reading is
-- touched: milestones are annotation only.
--
-- Exact output of
--     dotnet ef migrations script 20260923090000_AddAssignmentSeenAtToUserTeams \
--                                 20260929082822_AddTeamMilestones --idempotent
-- with only this header and the summary SELECT added.
--
-- Safe to run more than once (guarded on the migration history row), one
-- transaction. Run the whole file in pgAdmin (F5).
-- Rollback: DROP TABLE public."TeamMilestones";
--           DELETE FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20260929082822_AddTeamMilestones';
-- =============================================================================

START TRANSACTION;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20260929082822_AddTeamMilestones') THEN
    CREATE TABLE public."TeamMilestones" (
        "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
        "ProfileId" bigint NOT NULL,
        "UnitId" bigint NOT NULL,
        "Title" character varying(40) NOT NULL,
        "Description" character varying(200) NOT NULL,
        "MilestoneDate" date NOT NULL,
        "CreatedBy" integer,
        "UpdatedBy" integer,
        "CreatedAt" timestamp with time zone NOT NULL,
        "UpdatedAt" timestamp with time zone NOT NULL,
        "IsDel" boolean NOT NULL,
        CONSTRAINT "PK_TeamMilestones" PRIMARY KEY ("Id"),
        CONSTRAINT "FK_TeamMilestones_BusinessUnits_UnitId" FOREIGN KEY ("UnitId") REFERENCES "BusinessUnits" ("Id") ON DELETE RESTRICT,
        CONSTRAINT "FK_TeamMilestones_Profiles_ProfileId" FOREIGN KEY ("ProfileId") REFERENCES "Profiles" ("Id") ON DELETE RESTRICT
    );
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20260929082822_AddTeamMilestones') THEN
    CREATE INDEX "IX_TeamMilestones_Profile_Unit" ON public."TeamMilestones" ("ProfileId", "UnitId") WHERE "IsDel" = false;
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20260929082822_AddTeamMilestones') THEN
    CREATE INDEX "IX_TeamMilestones_Unit_Date" ON public."TeamMilestones" ("UnitId", "MilestoneDate") WHERE "IsDel" = false;
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20260929082822_AddTeamMilestones') THEN
    INSERT INTO "__EFMigrationsHistory" ("MigrationId", "ProductVersion")
    VALUES ('20260929082822_AddTeamMilestones', '9.0.5');
    END IF;
END $EF$;
COMMIT;



-- Summary
