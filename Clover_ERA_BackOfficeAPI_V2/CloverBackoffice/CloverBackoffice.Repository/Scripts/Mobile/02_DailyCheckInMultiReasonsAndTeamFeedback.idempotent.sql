-- Daily check-in: multi-select reasons, free-text-only answers, optional team feedback.
--
-- Mirrors migration 20260916143307_DailyCheckInMultiReasonsAndTeamFeedback.
-- Runs top to bottom in pgAdmin (F5) and is safe to re-run.
--
--   1. DailyFeedback.DailyReasonId -> nullable (answer with own free text only).
--      The existing foreign key (ON DELETE CASCADE) is kept as it is.
--   2. DailyFeedbackReasons      - every selected reason of a daily answer.
--   3. TeamDailyFeedbackReasons  - every selected reason of a team answer.
--   4. TeamFeedback              - "Any other feedback about your team?" (anonymous).
--   5. Backfill: each existing answer gets its one legacy reason as its reason set.
--   6. Records the EF migration.

BEGIN;

-- 1 ─────────────────────────────────────────────────────────────────────────
ALTER TABLE public."DailyFeedback" ALTER COLUMN "DailyReasonId" DROP NOT NULL;

-- 2 ─────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public."DailyFeedbackReasons" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "DailyFeedbackId" bigint NOT NULL,
    "DailyReasonId" bigint NOT NULL,
    CONSTRAINT "PK_DailyFeedbackReasons" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_DailyFeedbackReasons_DailyFeedback_DailyFeedbackId"
        FOREIGN KEY ("DailyFeedbackId") REFERENCES public."DailyFeedback" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_DailyFeedbackReasons_DailyReasons_DailyReasonId"
        FOREIGN KEY ("DailyReasonId") REFERENCES public."DailyReasons" ("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_DailyFeedbackReasons_DailyFeedbackId_DailyReasonId"
    ON public."DailyFeedbackReasons" ("DailyFeedbackId", "DailyReasonId");

CREATE INDEX IF NOT EXISTS "IX_DailyFeedbackReasons_DailyReasonId"
    ON public."DailyFeedbackReasons" ("DailyReasonId");

-- 3 ─────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public."TeamDailyFeedbackReasons" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "TeamDailyFeedbackId" bigint NOT NULL,
    "TeamDailyReasonId" bigint NOT NULL,
    CONSTRAINT "PK_TeamDailyFeedbackReasons" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_TeamDailyFeedbackReasons_TeamDailyFeedback_TeamDailyFeedbac~"
        FOREIGN KEY ("TeamDailyFeedbackId") REFERENCES public."TeamDailyFeedback" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_TeamDailyFeedbackReasons_TeamDailyReasons_TeamDailyReasonId"
        FOREIGN KEY ("TeamDailyReasonId") REFERENCES public."TeamDailyReasons" ("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_TeamDailyFeedbackReasons_TeamDailyFeedbackId_TeamDailyReaso~"
    ON public."TeamDailyFeedbackReasons" ("TeamDailyFeedbackId", "TeamDailyReasonId");

CREATE INDEX IF NOT EXISTS "IX_TeamDailyFeedbackReasons_TeamDailyReasonId"
    ON public."TeamDailyFeedbackReasons" ("TeamDailyReasonId");

-- 4 ─────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public."TeamFeedback" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "BusinessUnitId" bigint NOT NULL,
    "FeedbackText" character varying(300) NOT NULL,
    "ClientSubmittedAtUtc" timestamp with time zone NOT NULL,
    "SubmissionDateTime" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_TeamFeedback" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_TeamFeedback_BusinessUnits_BusinessUnitId"
        FOREIGN KEY ("BusinessUnitId") REFERENCES public."BusinessUnits" ("Id") ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS "IX_TeamFeedback_BusinessUnitId_SubmissionDateTime"
    ON public."TeamFeedback" ("BusinessUnitId", "SubmissionDateTime");

-- 5 ─────────────────────────────────────────────────────────────────────────
INSERT INTO public."DailyFeedbackReasons" ("DailyFeedbackId", "DailyReasonId")
SELECT df."Id", df."DailyReasonId"
FROM public."DailyFeedback" df
WHERE df."DailyReasonId" IS NOT NULL
ON CONFLICT ("DailyFeedbackId", "DailyReasonId") DO NOTHING;

INSERT INTO public."TeamDailyFeedbackReasons" ("TeamDailyFeedbackId", "TeamDailyReasonId")
SELECT tf."Id", tf."TeamDailyReasonId"
FROM public."TeamDailyFeedback" tf
ON CONFLICT ("TeamDailyFeedbackId", "TeamDailyReasonId") DO NOTHING;

-- 6 ─────────────────────────────────────────────────────────────────────────
INSERT INTO public."__EFMigrationsHistory" ("MigrationId", "ProductVersion")
SELECT '20260916143307_DailyCheckInMultiReasonsAndTeamFeedback', '9.0.5'
WHERE NOT EXISTS (
    SELECT 1 FROM public."__EFMigrationsHistory"
    WHERE "MigrationId" = '20260916143307_DailyCheckInMultiReasonsAndTeamFeedback');

COMMIT;

-- Summary ───────────────────────────────────────────────────────────────────
SELECT
    (SELECT is_nullable FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'DailyFeedback' AND column_name = 'DailyReasonId') AS dailyreasonid_nullable,
    (SELECT COUNT(*) FROM public."DailyFeedback")             AS daily_feedback_rows,
    (SELECT COUNT(*) FROM public."DailyFeedbackReasons")      AS daily_feedback_reason_rows,
    (SELECT COUNT(*) FROM public."TeamDailyFeedback")         AS team_daily_feedback_rows,
    (SELECT COUNT(*) FROM public."TeamDailyFeedbackReasons")  AS team_daily_feedback_reason_rows,
    (SELECT COUNT(*) FROM public."TeamFeedback")              AS team_feedback_rows,
    (SELECT COUNT(*) FROM public."__EFMigrationsHistory"
      WHERE "MigrationId" = '20260916143307_DailyCheckInMultiReasonsAndTeamFeedback') AS migration_recorded;
