-- =====================================================================
-- Clovera Personal App — Snapshot Report table
-- Run this manually against the CloverBackoffice PostgreSQL database.
--
-- Backs the CloveraPersonalSnapshot entity + DbSet (no EF migration is
-- used for this table; the schema is applied via this script).
-- Column types match exactly what EF Core / Npgsql maps the entity to,
-- so the entity reads/writes the table with no further configuration.
--
-- Idempotent: safe to run more than once.
-- =====================================================================

CREATE TABLE IF NOT EXISTS public."CloveraPersonalSnapshots"
(
    "Id"                      integer                  GENERATED BY DEFAULT AS IDENTITY,

    -- Run lifecycle
    "Status"                  character varying(20)    NOT NULL DEFAULT 'Queued',

    -- Source scope
    "CompanyId"               bigint                   NOT NULL,
    "UnitId"                  bigint                   NOT NULL,
    "FromDate"                timestamp with time zone NOT NULL,
    "ToDate"                  timestamp with time zone NOT NULL,
    "ModelUsed"               character varying(120),

    -- Parsed snapshot output
    "Headline"                text,
    "SummaryBody"             text,
    "ProductivityObservation" text,
    "PillarFraming"           text,
    "HighlightedPillarCode"   character varying(1),
    "HighlightedPillarLabel"  character varying(40),
    "HighlightedSmileyScore"  integer,
    "HighlightReason"         character varying(40),
    "NudgeTitle"              text,
    "NudgeRationale"          text,
    "NudgeAction"             text,
    "NudgeIntent"             character varying(20),
    "DrawingFromJson"         text,
    "RawResponseJson"         text,

    -- Telemetry
    "PromptTokens"            integer                  NOT NULL DEFAULT 0,
    "CompletionTokens"        integer                  NOT NULL DEFAULT 0,
    "TotalTokens"             integer                  NOT NULL DEFAULT 0,
    "GenerationSeconds"       double precision         NOT NULL DEFAULT 0,

    "ErrorMessage"            text,

    -- Audit / soft-delete
    "IsDel"                   boolean                  NOT NULL DEFAULT false,
    "CreatedAt"               timestamp with time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    "CompletedAt"             timestamp with time zone,
    "CreatedBy"               integer,

    CONSTRAINT "PK_CloveraPersonalSnapshots" PRIMARY KEY ("Id")
);

-- Helpful for the status/history lookups by unit + recency.
CREATE INDEX IF NOT EXISTS "IX_CloveraPersonalSnapshots_UnitId_CreatedAt"
    ON public."CloveraPersonalSnapshots" ("UnitId", "CreatedAt");
