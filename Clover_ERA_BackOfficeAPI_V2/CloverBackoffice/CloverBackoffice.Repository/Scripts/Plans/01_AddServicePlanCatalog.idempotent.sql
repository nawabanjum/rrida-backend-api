--
-- Five new tables. NOTHING EXISTING IS ALTERED: the legacy "Plans" table, licences
-- and subscriptions are untouched.
--
-- Exact output of
--     dotnet ef migrations script 20261110162523_ManagerActionsTeamOnly \
--                                 20261111145347_AddServicePlanCatalog --idempotent
-- with only this header and the summary SELECT added.
--
-- Safe to run more than once (guarded on the migration history row), one
-- transaction. Run the whole file in pgAdmin (F5). Run BEFORE deploying.
-- Rollback: DROP TABLE public."ServicePlanAuditLogs", public."ServicePlanFeatures",
--                      public."ServicePlanPriceTiers", public."PlanFeatures", public."ServicePlans";
--           DELETE FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20261111145347_AddServicePlanCatalog';
-- =============================================================================

