    (SELECT COUNT(*) FROM public."ServicePlanVersions")                   AS versions;

SELECT p."Code", v."VersionNumber", jsonb_array_length(v."Terms"->'PriceTiers') AS tiers,
       jsonb_array_length(v."Terms"->'Features') AS features
FROM public."ServicePlanVersions" v
JOIN public."ServicePlans" p ON p."Id" = v."ServicePlanId"
ORDER BY p."SortOrder", v."VersionNumber";
