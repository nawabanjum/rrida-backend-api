-- 05_AddServicePlanVersions.idempotent.sql
--
-- Plan versions: existing customers keep the terms they bought.
--   ServicePlanVersions                    frozen terms (price tiers, extension rule,
--                                          feature values) per plan version
--   CompanyLicenses.ServicePlanVersionId   the version a licence was bought on
--   CompanySubscriptions.ServicePlanVersionId
--
-- Seeds version 1 of every existing plan from its current values. Existing licences
-- stay NULL = version 1. Later plan edits save new versions; licences only move when
-- an admin calls POST api/admin/plans/{id}/migrate-licences.
--
-- Run AFTER 01-04. Safe to run more than once, one transaction. Run the whole file
-- in pgAdmin (F5).
--
-- Exact output of
--     dotnet ef migrations script 20261112074844_AddSubscriptionPlanUnitPrice \
--                                 20261112103931_AddServicePlanVersions --idempotent
-- with only this header and the summary SELECT added.
-- =============================================================================

