-- Mirrors EF migration 20260910090000_AddUserRolesAndPortfolioManagerAssignments
-- and records it in __EFMigrationsHistory so the app does not run it again.
--
-- Role ids: 1 Profile Admin, 2 Team Manager, 3 RRIDA Admin, 4 Portfolio Manager
-- Rank (highest first): 3 > 1 > 2 > 4
--
-- Users.UserGroupId is KEPT (derived = highest role). Do NOT run script 06.
-- =============================================================================

-- Clears a failed earlier attempt in this pgAdmin session.
-- "WARNING: there is no transaction in progress" is normal and harmless.
ROLLBACK;

BEGIN;

-- 1. UserRoles ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public."UserRoles" (
    "Id"          integer GENERATED BY DEFAULT AS IDENTITY,
    "UserId"      integer NOT NULL,
    "UserGroupId" integer NOT NULL,
    "CreatedBy"   integer NULL,
    "CreatedDate" timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "PK_UserRoles" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_UserRoles_Users_UserId"
        FOREIGN KEY ("UserId") REFERENCES public."Users" ("UserId") ON DELETE CASCADE,
    CONSTRAINT "FK_UserRoles_UserGroups_UserGroupId"
        FOREIGN KEY ("UserGroupId") REFERENCES public."UserGroups" ("Id") ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_UserRoles_UserId_UserGroupId"
    ON public."UserRoles" ("UserId", "UserGroupId");

CREATE INDEX IF NOT EXISTS "IX_UserRoles_UserGroupId"
    ON public."UserRoles" ("UserGroupId");

-- 2. Backfill: each user's current role --------------------------------------
INSERT INTO public."UserRoles" ("UserId", "UserGroupId")
SELECT u."UserId", u."UserGroupId"
  FROM public."Users" u
  JOIN public."UserGroups" g ON g."Id" = u."UserGroupId"
ON CONFLICT ("UserId", "UserGroupId") DO NOTHING;

-- 3. Backfill: anyone managing a team today also holds Team Manager (2) -------
INSERT INTO public."UserRoles" ("UserId", "UserGroupId")
SELECT m."UserId", 2
  FROM (
        SELECT DISTINCT ut."UserId"
          FROM public."UserTeams" ut
          JOIN public."Users" u ON u."UserId" = ut."UserId"
         WHERE ut."IsUnAssigned" = false
           AND u."IsDel" = false
           AND u."UserGroupId" <> 3
       ) m
ON CONFLICT ("UserId", "UserGroupId") DO NOTHING;

-- 4. Resync derived column: Users.UserGroupId = highest role ------------------
UPDATE public."Users" u
   SET "UserGroupId" = r."UserGroupId"
  FROM (
        SELECT DISTINCT ON ("UserId") "UserId", "UserGroupId"
          FROM public."UserRoles"
         ORDER BY "UserId",
                  CASE "UserGroupId" WHEN 3 THEN 0 WHEN 1 THEN 1
                                     WHEN 2 THEN 2 WHEN 4 THEN 3 ELSE 99 END
       ) r
 WHERE u."UserId" = r."UserId"
   AND u."UserGroupId" <> r."UserGroupId";

-- 5. PortfolioManagerAssignments ---------------------------------------------
CREATE TABLE IF NOT EXISTS public."PortfolioManagerAssignments" (
    "Id"                     integer GENERATED BY DEFAULT AS IDENTITY,
    "PortfolioManagerUserId" integer NOT NULL,
    "ManagerUserId"          integer NOT NULL,
    "ProfileId"              bigint  NOT NULL,
    "IsUnAssigned"           boolean NOT NULL DEFAULT false,
    "CreatedBy"              integer NOT NULL,
    "CreatedDate"            timestamp with time zone NOT NULL DEFAULT now(),
    "UnAssignedDate"         timestamp with time zone NULL,
    CONSTRAINT "PK_PortfolioManagerAssignments" PRIMARY KEY ("Id"),
    CONSTRAINT "CK_PortfolioManagerAssignments_NotSelf"
        CHECK ("PortfolioManagerUserId" <> "ManagerUserId"),
    CONSTRAINT "FK_PortfolioManagerAssignments_Users_PortfolioManagerUserId"
        FOREIGN KEY ("PortfolioManagerUserId") REFERENCES public."Users" ("UserId") ON DELETE RESTRICT,
    CONSTRAINT "FK_PortfolioManagerAssignments_Users_ManagerUserId"
        FOREIGN KEY ("ManagerUserId") REFERENCES public."Users" ("UserId") ON DELETE RESTRICT,
    CONSTRAINT "FK_PortfolioManagerAssignments_Profiles_ProfileId"
        FOREIGN KEY ("ProfileId") REFERENCES public."Profiles" ("Id") ON DELETE RESTRICT
);

-- One live Portfolio Manager per Team Manager.
CREATE UNIQUE INDEX IF NOT EXISTS "UX_PortfolioManagerAssignments_ManagerUserId_Active"
    ON public."PortfolioManagerAssignments" ("ManagerUserId")
    WHERE "IsUnAssigned" = false;

CREATE INDEX IF NOT EXISTS "IX_PortfolioManagerAssignments_PortfolioManager_IsUnAssigned"
    ON public."PortfolioManagerAssignments" ("PortfolioManagerUserId", "IsUnAssigned");

CREATE INDEX IF NOT EXISTS "IX_PortfolioManagerAssignments_ProfileId_IsUnAssigned"
    ON public."PortfolioManagerAssignments" ("ProfileId", "IsUnAssigned");

-- 6. UserTeams index ---------------------------------------------------------
CREATE INDEX IF NOT EXISTS "IX_UserTeams_UserId_IsUnAssigned"
    ON public."UserTeams" ("UserId", "IsUnAssigned");

-- 7. Guard: every user must have a role row for their UserGroupId -------------
DO $$
DECLARE missing integer;
BEGIN
    SELECT COUNT(*) INTO missing
      FROM public."Users" u
     WHERE NOT EXISTS (SELECT 1 FROM public."UserRoles" r
                        WHERE r."UserId" = u."UserId" AND r."UserGroupId" = u."UserGroupId");
    IF missing > 0 THEN
        RAISE EXCEPTION 'Backfill incomplete: % user(s) without a matching UserRoles row. Nothing applied.', missing;
    END IF;
END $$;

-- 8. Record the EF migration as applied ---------------------------------------
INSERT INTO public."__EFMigrationsHistory" ("MigrationId", "ProductVersion")
VALUES ('20260910090000_AddUserRolesAndPortfolioManagerAssignments', '9.0.1')
ON CONFLICT ("MigrationId") DO NOTHING;

COMMIT;

-- 9. Summary (read-only) -------------------------------------------------------
SELECT
    (SELECT COUNT(*) FROM public."Users")                        AS users,
    (SELECT COUNT(*) FROM public."UserRoles")                    AS user_roles_rows,
    (SELECT COUNT(*) FROM (SELECT "UserId" FROM public."UserRoles"
                            GROUP BY "UserId" HAVING COUNT(*) > 1) x) AS users_with_multiple_roles,
    (SELECT COUNT(*) FROM public."Users" u
      WHERE NOT EXISTS (SELECT 1 FROM public."UserRoles" r
                         WHERE r."UserId" = u."UserId" AND r."UserGroupId" = u."UserGroupId"))
                                                                  AS out_of_sync_must_be_0,
    (SELECT COUNT(*) FROM public."PortfolioManagerAssignments")  AS portfolio_rows,
    (SELECT COUNT(*) FROM public."__EFMigrationsHistory"
      WHERE "MigrationId" = '20260910090000_AddUserRolesAndPortfolioManagerAssignments') AS migration_recorded;


