-- =====================================================================
-- EranCoach — per-manager rolling memory (one row per manager)
-- Run this manually against the CloverBackoffice PostgreSQL database.
--
-- This table normally ships via EF migration AddEranCoachManagerMemory.
-- On databases where migrations were not applied, create it with this
-- script. Column types match the EranCoachManagerMemory entity exactly.
--
-- Idempotent: safe to run more than once.
-- =====================================================================

CREATE TABLE IF NOT EXISTS public."EranCoachManagerMemories"
(
    "Id"            integer                  GENERATED BY DEFAULT AS IDENTITY,
    "ManagerUserId" integer                  NOT NULL,
    "SummaryText"   text,
    "TurnCount"     integer                  NOT NULL DEFAULT 0,
    "CreatedAt"     timestamp with time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    "UpdatedAt"     timestamp with time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    "IsDel"         boolean                  NOT NULL DEFAULT false,
    CONSTRAINT "PK_EranCoachManagerMemories" PRIMARY KEY ("Id")
);

-- One active memory row per manager is read back each session.
CREATE INDEX IF NOT EXISTS "IX_EranCoachManagerMemories_ManagerUserId"
    ON public."EranCoachManagerMemories" ("ManagerUserId");
