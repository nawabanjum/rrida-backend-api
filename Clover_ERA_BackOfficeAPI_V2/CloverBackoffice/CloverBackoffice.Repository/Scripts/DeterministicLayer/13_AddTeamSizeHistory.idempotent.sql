-- =============================================================================
-- 13_AddTeamSizeHistory.idempotent.sql
--
-- Team size as the headcount (response rate + engine floor).
--
--   TeamSizeHistory  BusinessUnits.TeamSize, dated: one row per team per date the
--                    size was set or changed, in force until the next row. The
--                    response rate's "possible" and the engine's floor
--                    (max(2, 33% of headcount)) count against it, because app
--                    enrolments count devices, not people.
--
-- Part 1 is the exact output of
--     dotnet ef migrations script 20261112103931_AddServicePlanVersions \
--                                 20261116135604_AddTeamSizeHistory --idempotent
--
-- Part 2 seeds ONE row per team that has a size, effective TODAY (UTC). Today,
-- not the past, on purpose: the engine is replayed from day one every night, and
-- a size dated in the past would re-decide days already decided. From today the
-- engine counts the team size; every earlier day keeps the count it was decided on.
-- (The Team Health response rate uses the team size for its whole window at once:
-- it is a display only and stores nothing.) From then on the API writes a row
-- whenever a team's size is set or changed (ApplicationDbContext.SaveChanges).
--
-- NOTHING EXISTING IS ALTERED. One new table, rows inserted only.
--
-- MUST RUN BEFORE the code that reads TeamSizeHistory is deployed: saving a team
-- whose size changed, the Team Health timeline, Portfolio View, the roll-up and the
-- nightly engine run all read this table.
--
-- Safe to run more than once: part 1 is guarded on the migration history row,
-- part 2 only seeds a team that has no row yet. One transaction. Run the whole
-- file in pgAdmin (F5).
--
-- Rollback: DROP TABLE public."TeamSizeHistory";
--           DELETE FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20261116135604_AddTeamSizeHistory';
-- =============================================================================

START TRANSACTION;

-- ── Part 1: the table ────────────────────────────────────────────────────────

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20261116135604_AddTeamSizeHistory') THEN
    CREATE TABLE "TeamSizeHistory" (
        "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
        "BusinessUnitId" bigint NOT NULL,
        "TeamSize" integer,
        "EffectiveFrom" date NOT NULL,
        "CreatedAt" timestamp with time zone NOT NULL,
        "UpdatedAt" timestamp with time zone,
        CONSTRAINT "PK_TeamSizeHistory" PRIMARY KEY ("Id"),
        CONSTRAINT "FK_TeamSizeHistory_BusinessUnits_BusinessUnitId" FOREIGN KEY ("BusinessUnitId") REFERENCES "BusinessUnits" ("Id") ON DELETE RESTRICT
    );
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20261116135604_AddTeamSizeHistory') THEN
    CREATE UNIQUE INDEX "UX_TeamSizeHistory_Unit_EffectiveFrom" ON "TeamSizeHistory" ("BusinessUnitId", "EffectiveFrom");
    END IF;
END $EF$;

DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20261116135604_AddTeamSizeHistory') THEN
    INSERT INTO "__EFMigrationsHistory" ("MigrationId", "ProductVersion")
    VALUES ('20261116135604_AddTeamSizeHistory', '9.0.5');
    END IF;
END $EF$;

-- ── Part 2: today's size for every team that has one ─────────────────────────

INSERT INTO "TeamSizeHistory" ("BusinessUnitId", "TeamSize", "EffectiveFrom", "CreatedAt")
SELECT b."Id", b."TeamSize", (now() AT TIME ZONE 'utc')::date, now()
FROM "BusinessUnits" b
WHERE b."TeamSize" > 0
  AND NOT EXISTS (SELECT 1 FROM "TeamSizeHistory" h WHERE h."BusinessUnitId" = b."Id");

COMMIT;

-- ── Summary ──────────────────────────────────────────────────────────────────

SELECT count(*)                         AS teams_with_a_size,
       min("EffectiveFrom")             AS earliest_effective_from,
       max("EffectiveFrom")             AS latest_effective_from
FROM "TeamSizeHistory";
