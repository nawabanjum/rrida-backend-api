-- =============================================================================
-- 05_AddEngineConfirmationsAndDeclines.idempotent.sql
--
-- Deterministic layer, module 2 step 2.2: what the manager did.
--
--   EngineConfirmations   the 72-hour tap, per cycle per rung, with whether the
--                         worked-if condition was met
--   EngineDeclines        a stated contraindication the manager refused; recorded
--                         as a failed cycle with its reason
--
-- These are FACTS. The replay derives cycles from the answers, but a manager's tap
-- cannot be derived, so it is stored and fed back in on the day it happened. Each
-- row carries the date AND the asked-day index, because the two are plain integers
-- and confusing them moves the signal read along with the confirmation.
--
-- Nothing existing is touched. Safe to run more than once (F5 in pgAdmin).
-- Mirrors EF migration 20260926090000_AddEngineConfirmationsAndDeclines.
-- =============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public."EngineConfirmations" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "BusinessUnitId" bigint NOT NULL,
    "CycleKey" character varying(20) NOT NULL,
    "Rung" integer NOT NULL DEFAULT 1,
    "ConfirmedDate" date NOT NULL,
    "Day" integer NOT NULL,
    "AskedDayIndex" integer NOT NULL,
    "WorkedIfMet" boolean NOT NULL DEFAULT false,
    "ConfirmedByUserId" integer,
    "Source" character varying(50) NOT NULL DEFAULT 'manager',
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_EngineConfirmations" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EngineConfirmations_BusinessUnits_BusinessUnitId" FOREIGN KEY ("BusinessUnitId")
        REFERENCES public."BusinessUnits" ("Id") ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_EngineConfirmations_Unit_Cycle_Rung"
    ON public."EngineConfirmations" ("BusinessUnitId", "CycleKey", "Rung");

CREATE TABLE IF NOT EXISTS public."EngineDeclines" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "BusinessUnitId" bigint NOT NULL,
    "CycleKey" character varying(20) NOT NULL,
    "DeclinedDate" date NOT NULL,
    "Day" integer NOT NULL,
    "AskedDayIndex" integer NOT NULL,
    "Reason" character varying(500),
    "DeclinedByUserId" integer,
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_EngineDeclines" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EngineDeclines_BusinessUnits_BusinessUnitId" FOREIGN KEY ("BusinessUnitId")
        REFERENCES public."BusinessUnits" ("Id") ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_EngineDeclines_Unit_Cycle"
    ON public."EngineDeclines" ("BusinessUnitId", "CycleKey");


-- The EF migration 20260930153617_SyncEngineModelSnapshot carries this same SQL and
-- records itself when the pipeline runs. Nothing is written to __EFMigrationsHistory
-- here: every statement above is idempotent, so whichever runs second does nothing.

COMMIT;

-- Summary: the two tables and how many rows each holds.
SELECT t.table_name AS "Table",
       (xpath('/row/c/text()',
              query_to_xml(format('SELECT count(*) AS c FROM public.%I', t.table_name),
                           false, true, '')))[1]::text::bigint AS "Rows"
FROM information_schema.tables t
WHERE t.table_schema = 'public'
  AND t.table_name IN ('EngineConfirmations','EngineDeclines')
ORDER BY t.table_name;
