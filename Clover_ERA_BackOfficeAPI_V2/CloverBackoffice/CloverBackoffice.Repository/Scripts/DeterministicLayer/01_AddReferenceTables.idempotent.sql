-- =============================================================================
-- 01_AddReferenceTables.idempotent.sql
--
-- Deterministic layer, phase 1: the reference tables the engine reads.
--
-- Creates eight tables holding the handover pack's authored content — questions,
-- chips, issue files, actions, worksheets, worksheet phases and the capability
-- gap crosswalk — each row belonging to a RefDataVersion. The loader that fills
-- them comes in the next step; this script writes no data.
--
-- Nothing existing is touched: no table is altered and no row is changed.
-- Safe to run more than once (F5 in pgAdmin).
-- Mirrors EF migration 20260922090000_AddDeterministicReferenceData.
-- =============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public."RefDataVersions" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "SpecVersion" character varying(20) NOT NULL,
    "TallyKey" character varying(50) NOT NULL,
    "RunMinutesCap" integer NOT NULL DEFAULT 0,
    "QuestionCount" integer NOT NULL DEFAULT 0,
    "ChipCount" integer NOT NULL DEFAULT 0,
    "ActionCount" integer NOT NULL DEFAULT 0,
    "IssueFileCount" integer NOT NULL DEFAULT 0,
    "WorksheetCount" integer NOT NULL DEFAULT 0,
    "WorksheetPhaseCount" integer NOT NULL DEFAULT 0,
    "CapabilityFlagCount" integer NOT NULL DEFAULT 0,
    "Source" character varying(500),
    "LoadedAt" timestamp with time zone NOT NULL,
    "LoadedBy" integer,
    "IsActive" boolean NOT NULL DEFAULT false,
    CONSTRAINT "PK_RefDataVersions" PRIMARY KEY ("Id")
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RefDataVersions_IsActive"
    ON public."RefDataVersions" ("IsActive") WHERE "IsActive" = true;

CREATE TABLE IF NOT EXISTS public."RefQuestions" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "VersionId" bigint NOT NULL,
    "QuestionKey" integer NOT NULL,
    "Text" character varying(500) NOT NULL,
    "Element" character varying(100) NOT NULL,
    "Track" character varying(50) NOT NULL,
    CONSTRAINT "PK_RefQuestions" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_RefQuestions_RefDataVersions_VersionId" FOREIGN KEY ("VersionId")
        REFERENCES public."RefDataVersions" ("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RefQuestions_Version_QuestionKey"
    ON public."RefQuestions" ("VersionId", "QuestionKey");

CREATE TABLE IF NOT EXISTS public."RefChips" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "VersionId" bigint NOT NULL,
    "ChipKey" character varying(50) NOT NULL,
    "QuestionKey" integer NOT NULL,
    "Track" character varying(50) NOT NULL,
    "Element" character varying(100) NOT NULL,
    "Polarity" character varying(20) NOT NULL,
    "Text" character varying(300) NOT NULL,
    "Locus" character varying(20) NOT NULL,
    "IssueFileKey" character varying(30) NOT NULL,
    "CapabilityGap" boolean NOT NULL DEFAULT false,
    "Rung1AskKey" character varying(30),
    "Rung1TeamKey" character varying(30),
    "Rung1ContentKey" character varying(30),
    "Rung2Key" character varying(30),
    CONSTRAINT "PK_RefChips" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_RefChips_RefDataVersions_VersionId" FOREIGN KEY ("VersionId")
        REFERENCES public."RefDataVersions" ("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RefChips_Version_ChipKey"
    ON public."RefChips" ("VersionId", "ChipKey");
CREATE INDEX IF NOT EXISTS "IX_RefChips_Version_Question_Polarity"
    ON public."RefChips" ("VersionId", "QuestionKey", "Polarity");
CREATE INDEX IF NOT EXISTS "IX_RefChips_Version_IssueFile"
    ON public."RefChips" ("VersionId", "IssueFileKey");

CREATE TABLE IF NOT EXISTS public."RefIssueFiles" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "VersionId" bigint NOT NULL,
    "IssueFileKey" character varying(30) NOT NULL,
    "Issue" character varying(300) NOT NULL,
    "Pillar" character varying(100) NOT NULL,
    "ConversationalCount" integer NOT NULL DEFAULT 0,
    "StructuralCount" integer NOT NULL DEFAULT 0,
    "GestureCount" integer NOT NULL DEFAULT 0,
    CONSTRAINT "PK_RefIssueFiles" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_RefIssueFiles_RefDataVersions_VersionId" FOREIGN KEY ("VersionId")
        REFERENCES public."RefDataVersions" ("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RefIssueFiles_Version_IssueFileKey"
    ON public."RefIssueFiles" ("VersionId", "IssueFileKey");

CREATE TABLE IF NOT EXISTS public."RefActions" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "VersionId" bigint NOT NULL,
    "ActionKey" character varying(30) NOT NULL,
    "Text" character varying(1000) NOT NULL,
    "IssueFileKey" character varying(30) NOT NULL,
    "Issue" character varying(300),
    "Pillar" character varying(100),
    "Kind" character varying(30) NOT NULL,
    "Mode" character varying(30),
    "NoteType" character varying(20),
    "WorkedIf" character varying(1000),
    "Route" character varying(20),
    CONSTRAINT "PK_RefActions" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_RefActions_RefDataVersions_VersionId" FOREIGN KEY ("VersionId")
        REFERENCES public."RefDataVersions" ("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RefActions_Version_ActionKey"
    ON public."RefActions" ("VersionId", "ActionKey");
CREATE INDEX IF NOT EXISTS "IX_RefActions_Version_IssueFile_Kind"
    ON public."RefActions" ("VersionId", "IssueFileKey", "Kind");

CREATE TABLE IF NOT EXISTS public."RefWorksheets" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "VersionId" bigint NOT NULL,
    "Code" character varying(20) NOT NULL,
    "Title" character varying(300) NOT NULL,
    "Formerly" character varying(300),
    "Pillar" character varying(100),
    "Difficulty" integer,
    "TimeMinutes" character varying(50),
    "GroupSize" character varying(50),
    "Prerequisites" text[] NOT NULL DEFAULT '{}',
    "Contraindications" text[] NOT NULL DEFAULT '{}',
    CONSTRAINT "PK_RefWorksheets" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_RefWorksheets_RefDataVersions_VersionId" FOREIGN KEY ("VersionId")
        REFERENCES public."RefDataVersions" ("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RefWorksheets_Version_Code"
    ON public."RefWorksheets" ("VersionId", "Code");

CREATE TABLE IF NOT EXISTS public."RefWorksheetPhases" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "VersionId" bigint NOT NULL,
    "WorksheetId" bigint NOT NULL,
    "PhaseKey" character varying(30) NOT NULL,
    "WorksheetCode" character varying(20) NOT NULL,
    "Number" integer NOT NULL DEFAULT 0,
    "Title" character varying(300) NOT NULL,
    "MinutesMin" integer,
    "MinutesMax" integer,
    "Role" character varying(50),
    "Produces" character varying(1000),
    "RequiresPhases" text[] NOT NULL DEFAULT '{}',
    "Excerptable" boolean NOT NULL DEFAULT false,
    "Timing" character varying(20),
    "TimingNote" character varying(500),
    CONSTRAINT "PK_RefWorksheetPhases" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_RefWorksheetPhases_RefDataVersions_VersionId" FOREIGN KEY ("VersionId")
        REFERENCES public."RefDataVersions" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_RefWorksheetPhases_RefWorksheets_WorksheetId" FOREIGN KEY ("WorksheetId")
        REFERENCES public."RefWorksheets" ("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RefWorksheetPhases_Version_PhaseKey"
    ON public."RefWorksheetPhases" ("VersionId", "PhaseKey");
CREATE INDEX IF NOT EXISTS "IX_RefWorksheetPhases_Version_Worksheet_Number"
    ON public."RefWorksheetPhases" ("VersionId", "WorksheetCode", "Number");
CREATE INDEX IF NOT EXISTS "IX_RefWorksheetPhases_WorksheetId"
    ON public."RefWorksheetPhases" ("WorksheetId");

CREATE TABLE IF NOT EXISTS public."RefCapabilityFlags" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "VersionId" bigint NOT NULL,
    "IssueFileKey" character varying(30) NOT NULL,
    "CapabilityGap" boolean NOT NULL DEFAULT false,
    "Worksheets" text[] NOT NULL DEFAULT '{}',
    "Rationale" character varying(1000),
    "ContentPhases" text[] NOT NULL DEFAULT '{}',
    "LocusDiscoveryPhases" text[] NOT NULL DEFAULT '{}',
    "LocusDiscoveryActionKey" character varying(30),
    CONSTRAINT "PK_RefCapabilityFlags" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_RefCapabilityFlags_RefDataVersions_VersionId" FOREIGN KEY ("VersionId")
        REFERENCES public."RefDataVersions" ("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_RefCapabilityFlags_Version_IssueFileKey"
    ON public."RefCapabilityFlags" ("VersionId", "IssueFileKey");


-- The EF migration 20260930153617_SyncEngineModelSnapshot carries this same SQL and
-- records itself when the pipeline runs. Nothing is written to __EFMigrationsHistory
-- here: every statement above is idempotent, so whichever runs second does nothing.

COMMIT;

-- Summary: the eight tables and how many rows each holds (all zero until the
-- loader runs).
SELECT t.table_name AS "Table",
       (xpath('/row/c/text()',
              query_to_xml(format('SELECT count(*) AS c FROM public.%I', t.table_name),
                           false, true, '')))[1]::text::bigint AS "Rows"
FROM information_schema.tables t
WHERE t.table_schema = 'public'
  AND t.table_name IN ('RefDataVersions','RefQuestions','RefChips','RefIssueFiles',
                       'RefActions','RefWorksheets','RefWorksheetPhases','RefCapabilityFlags')
ORDER BY t.table_name;
