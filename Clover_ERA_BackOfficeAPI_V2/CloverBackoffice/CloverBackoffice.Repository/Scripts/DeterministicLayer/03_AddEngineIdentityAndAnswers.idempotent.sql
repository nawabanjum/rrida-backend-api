-- =============================================================================
-- 03_AddEngineIdentityAndAnswers.idempotent.sql
--
-- Deterministic layer, module 1 step 1.3: the facts the engine replays.
--
-- Creates five tables:
--   EngineMembers            who answers (no name, no email, no link to Users)
--   EngineTeamMemberships    effective-dated membership, so the floor's denominator
--                            can be asked for a PAST date
--   EngineTeamSettings       the team's start date and working week
--   EngineAnswers            one answer per member per track per day
--   EngineAnswerChips        zero to three chips per answer
--
-- Two rules are carried by constraints rather than by the application:
--   * one answer per member per track per day (a retry cannot become two votes);
--   * one OPEN membership per member per team (a double enrolment cannot inflate
--     the enrolled count).
--
-- Nothing existing is touched. The current DailyFeedback check-in chain is not
-- altered and keeps working exactly as it does today.
-- Safe to run more than once (F5 in pgAdmin).
-- Mirrors EF migration 20260924090000_AddEngineIdentityAndAnswers.
-- =============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public."EngineMembers" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "ProfileId" bigint NOT NULL,
    "TokenHash" character varying(64) NOT NULL,
    "EngineMemberKey" character varying(30) NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    "IsDel" boolean NOT NULL DEFAULT false,
    CONSTRAINT "PK_EngineMembers" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EngineMembers_Profiles_ProfileId" FOREIGN KEY ("ProfileId")
        REFERENCES public."Profiles" ("Id") ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_EngineMembers_TokenHash"
    ON public."EngineMembers" ("TokenHash");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_EngineMembers_EngineMemberKey"
    ON public."EngineMembers" ("EngineMemberKey");

CREATE TABLE IF NOT EXISTS public."EngineTeamMemberships" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "MemberId" bigint NOT NULL,
    "BusinessUnitId" bigint NOT NULL,
    "EffectiveFrom" date NOT NULL,
    "EffectiveTo" date,
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_EngineTeamMemberships" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EngineTeamMemberships_EngineMembers_MemberId" FOREIGN KEY ("MemberId")
        REFERENCES public."EngineMembers" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_EngineTeamMemberships_BusinessUnits_BusinessUnitId" FOREIGN KEY ("BusinessUnitId")
        REFERENCES public."BusinessUnits" ("Id") ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS "IX_EngineTeamMemberships_Unit_Period"
    ON public."EngineTeamMemberships" ("BusinessUnitId", "EffectiveFrom", "EffectiveTo");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_EngineTeamMemberships_Member_Unit_Open"
    ON public."EngineTeamMemberships" ("MemberId", "BusinessUnitId")
    WHERE "EffectiveTo" IS NULL;

CREATE TABLE IF NOT EXISTS public."EngineTeamSettings" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "BusinessUnitId" bigint NOT NULL,
    "StartDate" date NOT NULL,
    "WorkingWeek" character varying(30) NOT NULL DEFAULT 'mon-fri',
    "IsEnabled" boolean NOT NULL DEFAULT false,
    "CreatedAt" timestamp with time zone NOT NULL,
    "UpdatedAt" timestamp with time zone,
    "UpdatedBy" integer,
    CONSTRAINT "PK_EngineTeamSettings" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EngineTeamSettings_BusinessUnits_BusinessUnitId" FOREIGN KEY ("BusinessUnitId")
        REFERENCES public."BusinessUnits" ("Id") ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_EngineTeamSettings_BusinessUnitId"
    ON public."EngineTeamSettings" ("BusinessUnitId");

CREATE TABLE IF NOT EXISTS public."EngineAnswers" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "BusinessUnitId" bigint NOT NULL,
    "MemberId" bigint NOT NULL,
    "AnswerDate" date NOT NULL,
    "Day" integer NOT NULL,
    "AskedDayIndex" integer NOT NULL,
    "Track" character varying(20) NOT NULL,
    "QuestionKey" integer NOT NULL,
    "Level" character varying(20) NOT NULL,
    "FreeText" character varying(2000),
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_EngineAnswers" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EngineAnswers_BusinessUnits_BusinessUnitId" FOREIGN KEY ("BusinessUnitId")
        REFERENCES public."BusinessUnits" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_EngineAnswers_EngineMembers_MemberId" FOREIGN KEY ("MemberId")
        REFERENCES public."EngineMembers" ("Id") ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_EngineAnswers_Unit_Member_Track_Date"
    ON public."EngineAnswers" ("BusinessUnitId", "MemberId", "Track", "AnswerDate");
CREATE INDEX IF NOT EXISTS "IX_EngineAnswers_Unit_AskedDay"
    ON public."EngineAnswers" ("BusinessUnitId", "AskedDayIndex");

CREATE TABLE IF NOT EXISTS public."EngineAnswerChips" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "AnswerId" bigint NOT NULL,
    "ChipKey" character varying(50) NOT NULL,
    "Position" integer NOT NULL DEFAULT 0,
    CONSTRAINT "PK_EngineAnswerChips" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EngineAnswerChips_EngineAnswers_AnswerId" FOREIGN KEY ("AnswerId")
        REFERENCES public."EngineAnswers" ("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_EngineAnswerChips_Answer_Chip"
    ON public."EngineAnswerChips" ("AnswerId", "ChipKey");


-- The EF migration 20260930153617_SyncEngineModelSnapshot carries this same SQL and
-- records itself when the pipeline runs. Nothing is written to __EFMigrationsHistory
-- here: every statement above is idempotent, so whichever runs second does nothing.

COMMIT;

-- Summary: the five tables and how many rows each holds (all zero on a first run).
SELECT t.table_name AS "Table",
       (xpath('/row/c/text()',
              query_to_xml(format('SELECT count(*) AS c FROM public.%I', t.table_name),
                           false, true, '')))[1]::text::bigint AS "Rows"
FROM information_schema.tables t
WHERE t.table_schema = 'public'
  AND t.table_name IN ('EngineMembers','EngineTeamMemberships','EngineTeamSettings',
                       'EngineAnswers','EngineAnswerChips')
ORDER BY t.table_name;
