-- =============================================================================
-- 06_AddEngineLlmCalls.idempotent.sql
--
-- Deterministic layer, module 3 step 3.2: Eran.
--
--   EngineFeedItems.Prose / ProseGeneratedAt   the sentences the manager reads,
--                                              written once per feed item
--   EngineLlmCalls                             every call in full: system prompt,
--                                              payload sent, response, model,
--                                              duration, error
--
-- Eran's output is shown to managers and to teams, so what was generated and from
-- what has to stay answerable. Phrasing once also means re-running a day neither
-- re-bills nor changes wording a manager has already read.
--
-- Adds two columns and one table. Nothing existing is altered and no row changed.
-- Safe to run more than once (F5 in pgAdmin).
-- RUN 04_AddEngineRunResults.idempotent.sql FIRST — this needs EngineFeedItems.
-- Mirrors EF migration 20260927090000_AddEngineLlmCalls.
-- =============================================================================

BEGIN;

DO $$
BEGIN
    IF to_regclass('public."EngineFeedItems"') IS NULL THEN
        RAISE EXCEPTION 'EngineFeedItems does not exist. Run 04_AddEngineRunResults.idempotent.sql first.';
    END IF;
END $$;

ALTER TABLE public."EngineFeedItems"
    ADD COLUMN IF NOT EXISTS "Prose" character varying(4000),
    ADD COLUMN IF NOT EXISTS "ProseGeneratedAt" timestamp with time zone;

CREATE TABLE IF NOT EXISTS public."EngineLlmCalls" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "BusinessUnitId" bigint NOT NULL,
    "FeedKey" character varying(20),
    "PromptType" character varying(50) NOT NULL,
    "Day" integer NOT NULL DEFAULT 0,
    "SystemPrompt" text NOT NULL,
    "UserContent" text NOT NULL,
    "Response" text,
    "Model" character varying(200),
    "DurationMs" integer,
    "Error" character varying(1000),
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_EngineLlmCalls" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EngineLlmCalls_BusinessUnits_BusinessUnitId" FOREIGN KEY ("BusinessUnitId")
        REFERENCES public."BusinessUnits" ("Id") ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS "IX_EngineLlmCalls_Unit_Day"
    ON public."EngineLlmCalls" ("BusinessUnitId", "Day");


-- The EF migration 20260930153617_SyncEngineModelSnapshot carries this same SQL and
-- records itself when the pipeline runs. Nothing is written to __EFMigrationsHistory
-- here: every statement above is idempotent, so whichever runs second does nothing.

COMMIT;

-- Summary: the new table, and the two columns on the feed.
SELECT 'EngineLlmCalls' AS "Object",
       (SELECT count(*) FROM public."EngineLlmCalls")::text AS "Detail"
UNION ALL
SELECT 'EngineFeedItems.' || column_name, data_type
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'EngineFeedItems'
  AND column_name IN ('Prose', 'ProseGeneratedAt')
ORDER BY 1;
