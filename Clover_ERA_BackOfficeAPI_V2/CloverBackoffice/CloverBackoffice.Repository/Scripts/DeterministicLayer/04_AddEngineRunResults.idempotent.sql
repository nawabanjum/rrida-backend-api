-- =============================================================================
-- 04_AddEngineRunResults.idempotent.sql
--
-- Deterministic layer, module 2 step 2.1: where a run's results land.
--
-- Creates five tables:
--   EngineStateDaily        one resolved state record per team per day, flat columns
--                           for reading plus the whole record as jsonb evidence
--   EngineCycles            one active action, selection to resolution
--   EngineCycleDeliveries   what was actually delivered on each rung, snapshotted
--   EngineFeedItems         what Eran is handed, payload as jsonb
--   EngineTeamNotes         the note the team sees
--
-- Everything here is DERIVED: the replay rebuilds it from the recorded answers and
-- confirmations. Each table therefore carries a natural key with a unique index, so
-- writing the same day twice updates one row rather than duplicating history.
--
-- Nothing existing is touched. Safe to run more than once (F5 in pgAdmin).
-- Mirrors EF migration 20260925090000_AddEngineRunResults.
-- =============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public."EngineStateDaily" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "BusinessUnitId" bigint NOT NULL,
    "Day" integer NOT NULL,
    "Schema" character varying(50) NOT NULL,
    "ConfigId" character varying(50) NOT NULL,
    "Vertical" character varying(20) NOT NULL,
    "Horizontal" character varying(20) NOT NULL,
    "HeadwindsFlag" boolean NOT NULL DEFAULT false,
    "Limb" character varying(20),
    "OpenedDay" integer,
    "ConcentrationReading" character varying(30),
    "ConcentrationTopShare" double precision,
    "ClassifierZ" double precision,
    "ClassifierHorizontal" character varying(20),
    "WatchExposed" boolean NOT NULL DEFAULT false,
    "RecordJson" jsonb NOT NULL,
    "WrittenAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_EngineStateDaily" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EngineStateDaily_BusinessUnits_BusinessUnitId" FOREIGN KEY ("BusinessUnitId")
        REFERENCES public."BusinessUnits" ("Id") ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_EngineStateDaily_Unit_Day"
    ON public."EngineStateDaily" ("BusinessUnitId", "Day");

CREATE TABLE IF NOT EXISTS public."EngineCycles" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "BusinessUnitId" bigint NOT NULL,
    "CycleKey" character varying(20) NOT NULL,
    "CycleIndex" integer NOT NULL DEFAULT 0,
    "IssueFileKey" character varying(30) NOT NULL,
    "Issue" character varying(300),
    "TriggeringChipKey" character varying(50),
    "TriggeringQuestionKey" integer NOT NULL DEFAULT 0,
    "TallyActionKey" character varying(30),
    "Route" character varying(20),
    "ShareText" character varying(100),
    "SelectedDay" integer NOT NULL DEFAULT 0,
    "DeliveredDay" integer NOT NULL DEFAULT 0,
    "ConfirmationDueDay" integer NOT NULL DEFAULT 0,
    "SignalReadDay" integer,
    "ResolvedDay" integer,
    "Outcome" character varying(30),
    "Rung2Skipped" boolean NOT NULL DEFAULT false,
    "Rung2SkipReason" character varying(300),
    "DeclinedDay" integer,
    "DeclineReason" character varying(500),
    "WrittenAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_EngineCycles" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EngineCycles_BusinessUnits_BusinessUnitId" FOREIGN KEY ("BusinessUnitId")
        REFERENCES public."BusinessUnits" ("Id") ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_EngineCycles_Unit_CycleKey"
    ON public."EngineCycles" ("BusinessUnitId", "CycleKey");
CREATE INDEX IF NOT EXISTS "IX_EngineCycles_Unit_Outcome"
    ON public."EngineCycles" ("BusinessUnitId", "Outcome");

CREATE TABLE IF NOT EXISTS public."EngineCycleDeliveries" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "CycleId" bigint NOT NULL,
    "Rung" integer NOT NULL,
    "Route" character varying(20),
    "ActionKey" character varying(30) NOT NULL,
    "DeliveredText" character varying(1000),
    "DeliveredWorkedIf" character varying(1000),
    "DeliveredWorksheetCode" character varying(20),
    "DeliveredPhaseRun" text[] NOT NULL DEFAULT '{}',
    "DeliveredDay" integer NOT NULL DEFAULT 0,
    "ConfirmedDay" integer,
    "WorkedIfMet" boolean,
    "SignalReadDay" integer,
    "SignalMoved" boolean,
    "HowRead" character varying(100),
    "Outcome" character varying(30),
    CONSTRAINT "PK_EngineCycleDeliveries" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EngineCycleDeliveries_EngineCycles_CycleId" FOREIGN KEY ("CycleId")
        REFERENCES public."EngineCycles" ("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_EngineCycleDeliveries_Cycle_Rung"
    ON public."EngineCycleDeliveries" ("CycleId", "Rung");

CREATE TABLE IF NOT EXISTS public."EngineFeedItems" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "BusinessUnitId" bigint NOT NULL,
    "FeedKey" character varying(20) NOT NULL,
    "Day" integer NOT NULL,
    "Kind" character varying(50) NOT NULL,
    "CycleKey" character varying(20),
    "Rung" integer,
    "Situation" character varying(200),
    "NoteType" character varying(20),
    "PayloadJson" jsonb NOT NULL,
    "WrittenAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_EngineFeedItems" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EngineFeedItems_BusinessUnits_BusinessUnitId" FOREIGN KEY ("BusinessUnitId")
        REFERENCES public."BusinessUnits" ("Id") ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_EngineFeedItems_Unit_FeedKey"
    ON public."EngineFeedItems" ("BusinessUnitId", "FeedKey");
CREATE INDEX IF NOT EXISTS "IX_EngineFeedItems_Unit_Day"
    ON public."EngineFeedItems" ("BusinessUnitId", "Day");

CREATE TABLE IF NOT EXISTS public."EngineTeamNotes" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "BusinessUnitId" bigint NOT NULL,
    "CycleKey" character varying(20),
    "Day" integer NOT NULL,
    "NoteType" character varying(20),
    "Text" character varying(2000),
    "IssuedAt" timestamp with time zone,
    "WrittenAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_EngineTeamNotes" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EngineTeamNotes_BusinessUnits_BusinessUnitId" FOREIGN KEY ("BusinessUnitId")
        REFERENCES public."BusinessUnits" ("Id") ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_EngineTeamNotes_Unit_Cycle_Day"
    ON public."EngineTeamNotes" ("BusinessUnitId", "CycleKey", "Day");


-- The EF migration 20260930153617_SyncEngineModelSnapshot carries this same SQL and
-- records itself when the pipeline runs. Nothing is written to __EFMigrationsHistory
-- here: every statement above is idempotent, so whichever runs second does nothing.

COMMIT;

-- Summary: the five tables and how many rows each holds (all zero until a run).
SELECT t.table_name AS "Table",
       (xpath('/row/c/text()',
              query_to_xml(format('SELECT count(*) AS c FROM public.%I', t.table_name),
                           false, true, '')))[1]::text::bigint AS "Rows"
FROM information_schema.tables t
WHERE t.table_schema = 'public'
  AND t.table_name IN ('EngineStateDaily','EngineCycles','EngineCycleDeliveries',
                       'EngineFeedItems','EngineTeamNotes')
ORDER BY t.table_name;
